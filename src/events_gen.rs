//! `cs2-sdk events <gameevents.json|dump dir> -o <header>`: typed C++ header
//! for every game event, generated offline from the dumped registry.
//!
//! The header carries layout and metadata only. It does not read live events;
//! it gives consumers a struct per event (field names, types, order) and a
//! lookup table, so adding an event consumer does not mean typing field names
//! by hand.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use serde_json::Value;

#[derive(Debug, clap::Args)]
pub struct EventsArgs {
    /// `gameevents.json`, or a dump directory that contains it.
    pub input: PathBuf,
    /// Header to write.
    #[arg(short, long, default_value = "gameevents.hpp")]
    pub output: PathBuf,
    /// C++ namespace for the generated declarations.
    #[arg(long, default_value = "cs2::events")]
    pub namespace: String,
}

const KEYWORDS: &[&str] = &[
    "alignas", "and", "auto", "bool", "break", "case", "char", "class", "const", "continue", "default",
    "delete", "do", "double", "else", "enum", "explicit", "extern", "false", "float", "for", "if", "int",
    "long", "namespace", "new", "not", "operator", "or", "private", "protected", "public", "register",
    "return", "short", "signed", "sizeof", "static", "struct", "switch", "template", "this", "true",
    "typedef", "union", "unsigned", "using", "virtual", "void", "volatile", "while", "xor",
];

struct Event {
    name: String,
    id: i64,
    local: bool,
    fields: Vec<(String, String)>,
}

/// (C++ value type, FieldType enumerator) for a dumped field type.
fn map_type(t: &str) -> Option<(&'static str, &'static str)> {
    Some(match t {
        "bool" => ("bool", "Bool"),
        "byte" => ("std::uint8_t", "Byte"),
        "int16" => ("std::int16_t", "Int16"),
        "int32" => ("std::int32_t", "Int32"),
        "uint64" => ("std::uint64_t", "UInt64"),
        "float" => ("float", "Float"),
        "string" => ("const char*", "String"),
        "player_controller" => ("PlayerControllerRef", "PlayerController"),
        "player_pawn" => ("PlayerPawnRef", "PlayerPawn"),
        // Used by the demo_* events for opaque lists.
        "local" => ("OpaqueLocal", "Local"),
        _ => return None,
    })
}

fn ident(name: &str) -> String {
    let mut s: String = name.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if s.chars().next().is_none_or(|c| c.is_ascii_digit()) || KEYWORDS.contains(&s.as_str()) {
        s.push('_');
    }
    s
}

fn resolve_input(p: &Path) -> Result<PathBuf> {
    if p.is_file() {
        return Ok(p.to_path_buf());
    }
    for rel in ["gameevents/gameevents.json", "gameevents.json", "events/gameevents.json"] {
        let c = p.join(rel);
        if c.is_file() {
            return Ok(c);
        }
    }
    bail!("no gameevents.json found at or under {}", p.display())
}

fn parse(path: &Path) -> Result<(Option<u64>, Vec<Event>)> {
    let text = std::fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
    let v: Value = serde_json::from_str(text.trim_start_matches('\u{feff}'))?;
    let build = v.get("build_number").and_then(Value::as_u64);
    let arr = v.get("events").and_then(Value::as_array).context("`events` array missing")?;
    let mut events = Vec::with_capacity(arr.len());
    for e in arr {
        let name = e.get("name").and_then(Value::as_str).context("event without name")?.to_string();
        let fields = e
            .get("fields")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .map(|f| {
                        (
                            f.get("name").and_then(Value::as_str).unwrap_or_default().to_string(),
                            f.get("type").and_then(Value::as_str).unwrap_or_default().to_string(),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        events.push(Event {
            name,
            // The dump stores "no id" as 0xFFFFFFFF; keep it as -1 so it fits int32_t.
            id: e.get("id").and_then(Value::as_i64).map_or(-1, |v| i64::from(v as i32)),
            local: e.get("local").and_then(Value::as_bool).unwrap_or(false),
            fields,
        });
    }
    events.sort_by(|a, b| a.name.cmp(&b.name));
    Ok((build, events))
}

fn render(build: Option<u64>, events: &[Event], ns: &str) -> Result<String> {
    let mut o = String::new();
    let build = build.map_or("unknown".to_string(), |b| b.to_string());
    writeln!(o, "// Generated by `cs2-sdk events` from gameevents.json (build {build}, {} events).", events.len())?;
    writeln!(o, "// Do not edit. Layout only: field order, names and types of each event.")?;
    writeln!(o, "// `kId` is the registry id of that build and is not stable across builds; key on `kName`.")?;
    o.push_str("#pragma once\n\n#include <cstddef>\n#include <cstdint>\n#include <string_view>\n\n");
    writeln!(o, "namespace {ns} {{\n")?;
    o.push_str(
        "// Raw values as carried by the event; their meaning is not decoded here.\n\
         struct PlayerControllerRef { std::int32_t raw; };\n\
         struct PlayerPawnRef { std::int32_t raw; };\n\
         struct OpaqueLocal { std::uint64_t raw; };\n\n\
         enum class FieldType : std::uint8_t {\n    Bool, Byte, Int16, Int32, UInt64, Float, String,\n    PlayerController, PlayerPawn, Local,\n};\n\n\
         struct FieldInfo {\n    std::string_view name;\n    FieldType type;\n};\n\n\
         struct EventInfo {\n    std::string_view name;\n    std::int32_t id;\n    bool local;\n    const FieldInfo* fields;\n    std::size_t field_count;\n};\n\n",
    );

    for e in events {
        let sname = ident(&e.name);
        writeln!(o, "struct {sname} {{")?;
        writeln!(o, "    static constexpr std::string_view kName = \"{}\";", e.name)?;
        writeln!(o, "    static constexpr std::int32_t kId = {};", e.id)?;
        for (fname, ftype) in &e.fields {
            let Some((cpp, _)) = map_type(ftype) else {
                bail!("event {}: unknown field type `{ftype}` (extend map_type)", e.name);
            };
            writeln!(o, "    {cpp} {};", ident(fname))?;
        }
        o.push_str("};\n\n");
    }

    for e in events.iter().filter(|e| !e.fields.is_empty()) {
        writeln!(o, "inline constexpr FieldInfo {}_fields[] = {{", ident(&e.name))?;
        for (fname, ftype) in &e.fields {
            let (_, en) = map_type(ftype).expect("checked above");
            writeln!(o, "    {{\"{fname}\", FieldType::{en}}},")?;
        }
        o.push_str("};\n\n");
    }

    o.push_str("inline constexpr EventInfo kEvents[] = {\n");
    for e in events {
        let sname = ident(&e.name);
        let (ptr, count) = if e.fields.is_empty() {
            ("nullptr".to_string(), "0".to_string())
        } else {
            (format!("{sname}_fields"), format!("{}", e.fields.len()))
        };
        writeln!(o, "    {{\"{}\", {}, {}, {ptr}, {count}}},", e.name, e.id, e.local)?;
    }
    o.push_str("};\n\n");
    o.push_str(
        "constexpr const EventInfo* find_event(std::string_view name) {\n    for (const EventInfo& e : kEvents) {\n        if (e.name == name) return &e;\n    }\n    return nullptr;\n}\n\n",
    );
    writeln!(o, "}}  // namespace {ns}")?;
    Ok(o)
}

pub fn run(args: &EventsArgs) -> Result<i32> {
    let path = resolve_input(&args.input)?;
    let (build, events) = parse(&path)?;
    let text = render(build, &events, &args.namespace)?;
    if let Some(dir) = args.output.parent().filter(|d| !d.as_os_str().is_empty()) {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&args.output, text).with_context(|| format!("write {}", args.output.display()))?;
    eprintln!("wrote {} ({} events)", args.output.display(), events.len());
    Ok(0)
}
